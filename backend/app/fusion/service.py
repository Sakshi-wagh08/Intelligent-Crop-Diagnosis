import asyncio
import logging
from typing import Optional, Dict, Any, List
from datetime import datetime, timezone

from backend.app.schemas.vision import DiagnosisResult, SeverityResult, VisionDiagnosisResponse
from backend.app.schemas.soil import SoilTelemetryResponse
from backend.app.schemas.fusion import (
    FusionRecommendationResponse,
    TelemetryFusionSummary,
    TreatmentDetail,
    DosageCalculationBreakdown,
    SafetyAssessment,
)
from backend.app.vision.service import vision_service, VisionService
from backend.app.telemetry.service import soil_telemetry_service, SoilTelemetryService
from backend.app.telemetry.weather import get_spray_weather_advisory
from backend.app.fusion.knowledge_base import AgronomicKnowledgeBase
from backend.app.fusion.safety import SafetyComplianceEngine
from backend.app.fusion.engine import DosageCalculator

logger = logging.getLogger(__name__)

DISCLAIMER_ADVISORY = (
    "ADVISORY DISCLAIMER: This chemical recommendation is generated by an algorithmic multimodal fusion system "
    "based on verified public agricultural extension packages-of-practices and CIBRC label registrations. "
    "Dosages are strictly bounded by statutory label maximums (D_label_max). Farmers must verify with a certified "
    "Agricultural Extension Officer and thoroughly inspect the physical product container label before field application."
)


class FusionService:
    """Central multimodal fusion orchestrator connecting vision, soil telemetry, and agronomic knowledge."""

    def __init__(
        self,
        vision_svc: Optional[VisionService] = None,
        soil_svc: Optional[SoilTelemetryService] = None,
    ):
        self.vision_service = vision_svc or vision_service
        self.soil_service = soil_svc or soil_telemetry_service

    async def fuse_and_recommend(
        self,
        crop_name: str,
        crop_stage: str,
        latitude: float,
        longitude: float,
        days_to_harvest: Optional[int] = None,
        co_applied_chemicals: Optional[List[str]] = None,
        image_bytes: Optional[bytes] = None,
        precomputed_diagnosis: Optional[DiagnosisResult] = None,
        precomputed_severity: Optional[SeverityResult] = None,
        diagnosed_disease_override: Optional[str] = None,
        diagnostic_confidence_override: Optional[float] = None,
        allow_demo: bool = False,
    ) -> FusionRecommendationResponse:
        """Executes end-to-end multimodal data fusion and bounded dosage recommendation."""

        # ----------------------------------------------------------------------
        # Step 1: Acquire Visual Diagnosis and Severity Telemetry
        # ----------------------------------------------------------------------
        diagnosis: Optional[DiagnosisResult] = precomputed_diagnosis
        severity: Optional[SeverityResult] = precomputed_severity

        if image_bytes:
            vision_resp = self.vision_service.diagnose_image(image_bytes)
            diag_data = vision_resp.get("diagnosis")
            if diag_data:
                if isinstance(diag_data, DiagnosisResult):
                    diagnosis = diag_data
                elif isinstance(diag_data, dict):
                    diagnosis = DiagnosisResult(**diag_data)

            sev_data = vision_resp.get("severity_estimation")
            if sev_data:
                if isinstance(sev_data, SeverityResult):
                    severity = sev_data
                elif isinstance(sev_data, dict):
                    severity = SeverityResult(**sev_data)

        if not diagnosis and diagnosed_disease_override:
            # Synthetic / pre-diagnosed telemetry input
            conf = diagnostic_confidence_override if diagnostic_confidence_override is not None else 0.85
            is_healthy = "healthy" in diagnosed_disease_override.lower()
            diagnosis = DiagnosisResult(
                predicted_class=f"{crop_name}___{diagnosed_disease_override}",
                crop=crop_name,
                disease=diagnosed_disease_override,
                is_healthy=is_healthy,
                confidence=conf,
                is_confident=(conf >= 0.70),
                confidence_threshold=0.70,
                top_k_predictions=[],
                is_unsupported_or_uncertain=False,
            )

        if not diagnosis:
            # No diagnostic information available
            telemetry_summary = TelemetryFusionSummary(
                crop=crop_name,
                disease="Undiagnosed",
                diagnostic_confidence=0.0,
                is_healthy=False,
                severity_ratio=0.0,
                severity_tier="Undetected",
                severity_is_reliable=False,
                soil_data_status="unavailable",
                soil_source="None",
            )
            safety = SafetyAssessment(
                is_safe_to_apply=False,
                safety_status="REJECTED_DIAGNOSIS_MISSING",
                confidence_check_passed=False,
                phi_check_passed=True,
                compatibility_check_passed=True,
                verification_check_passed=False,
                warnings=["Missing visual diagnostic telemetry. A valid plant leaf image or diagnosis is mandatory."],
                protective_equipment=[],
                environmental_precautions="No chemical action permitted without verified diagnosis.",
            )
            return FusionRecommendationResponse(
                recommendation_available=False,
                status="DIAGNOSIS_UNAVAILABLE",
                status_message="Visual disease diagnosis is missing or unavailable.",
                telemetry_summary=telemetry_summary,
                safety_assessment=safety,
                treatment=None,
                dosage_breakdown=None,
                advisory_notice=DISCLAIMER_ADVISORY,
            )

        # ----------------------------------------------------------------------
        # Step 2: Query Geospatial Soil Telemetry & Live Weather Concurrently
        # ----------------------------------------------------------------------
        soil_resp, weather_adv = await asyncio.gather(
            self.soil_service.get_telemetry(
                latitude=latitude,
                longitude=longitude,
                depth="0-5cm",
            ),
            get_spray_weather_advisory(latitude=latitude, longitude=longitude),
        )

        # Compute soil-adjusted fertilizer plan for the crop & stage
        fertilizer_plan = AgronomicKnowledgeBase.get_fertilizer_plan(crop=crop_name, stage=crop_stage)
        fertilizer_rec: Optional[Dict[str, Any]] = None
        if fertilizer_plan:
            fert_calc = DosageCalculator.compute_dosage(
                treatment=fertilizer_plan,
                severity_result=None,
                soil_result=soil_resp,
            )
            fertilizer_rec = {
                "product_name": fertilizer_plan["registered_product_name"],
                "active_ingredient": fertilizer_plan["active_ingredient"],
                "reference_concentration_Cr": fertilizer_plan["standard_concentration_Cr"],
                "nutrient_focus": fertilizer_plan["nutrient_focus"],
                "base_dose_D0": fert_calc.base_dose_D0,
                "soil_factor_Fs": fert_calc.soil_factor_Fs,
                "soil_factor_status": fert_calc.soil_factor_status,
                "final_prescribed_dose": fert_calc.final_prescribed_dose,
                "max_label_dose_cap": fert_calc.max_label_dose_cap,
                "dose_unit": fert_calc.dose_unit,
                "application_method": fertilizer_plan["application_method"],
                "instructions": fertilizer_plan["label_restrictions"],
                "source_citation": fertilizer_plan["source_citation"],
            }

        soil_pH = None
        soil_texture = None
        soil_soc = None
        if soil_resp.parameters:
            soil_pH = soil_resp.parameters.pH
            soil_texture = soil_resp.parameters.soil_texture_class
            soil_soc = soil_resp.parameters.organic_carbon_g_kg

        telemetry_summary = TelemetryFusionSummary(
            crop=crop_name,
            disease=diagnosis.disease,
            diagnostic_confidence=round(diagnosis.confidence, 3),
            is_healthy=diagnosis.is_healthy,
            severity_ratio=round(severity.lesion_to_leaf_ratio, 3) if severity else 0.0,
            severity_tier=severity.severity_tier if severity else "Low",
            severity_is_reliable=severity.is_reliable if severity else False,
            soil_data_status=soil_resp.data_status,
            soil_source=soil_resp.telemetry_source,
            soil_pH=soil_pH,
            soil_texture=soil_texture,
            soil_organic_carbon_g_kg=soil_soc,
        )

        # ----------------------------------------------------------------------
        # Step 3: Handle Healthy Plant Case
        # ----------------------------------------------------------------------
        if diagnosis.is_healthy:
            safety = SafetyComplianceEngine.evaluate_safety(
                crop=crop_name,
                diagnosed_disease=diagnosis.disease,
                is_healthy=True,
                diagnostic_confidence=diagnosis.confidence,
                treatment=None,
            )
            fert_tip = (
                f"For healthy growth, apply {fertilizer_rec['final_prescribed_dose']} {fertilizer_rec['dose_unit']} "
                f"of {fertilizer_rec['product_name']} per acre ({fertilizer_rec['instructions']})."
                if fertilizer_rec
                else "Keep watering normally and check leaves weekly."
            )
            farmer_summary = {
                "headline": f"Good news! Your {crop_name} leaf looks healthy.",
                "what_to_do": "No chemical pesticide spray is needed.",
                "how_to_mix": "Do not spray any fungicide or pesticide.",
                "safety_tip": "Inspect your field once a week for early spots.",
                "weather_tip": weather_adv.get("advisory", ""),
                "fertilizer_tip": fert_tip,
                "speech_text": (
                    f"Good news. Your {crop_name} crop looks healthy, so no pesticide spray is needed. {fert_tip}"
                ),
            }
            return FusionRecommendationResponse(
                recommendation_available=True,
                status="HEALTHY_NO_TREATMENT_NEEDED",
                status_message="Plant diagnosed as healthy. Chemical intervention is not recommended.",
                telemetry_summary=telemetry_summary,
                safety_assessment=safety,
                treatment=None,
                dosage_breakdown=None,
                fertilizer_recommendation=fertilizer_rec,
                weather_advisory=weather_adv,
                farmer_summary=farmer_summary,
                advisory_notice=DISCLAIMER_ADVISORY,
            )

        # ----------------------------------------------------------------------
        # Step 4: Agronomic Treatment Lookup
        # ----------------------------------------------------------------------
        treatment_data = AgronomicKnowledgeBase.get_treatment(
            crop=crop_name,
            disease=diagnosis.disease,
            stage=crop_stage,
            allow_demo=allow_demo,
        )

        # ----------------------------------------------------------------------
        # Step 5: Safety and Regulatory Compliance Evaluation
        # ----------------------------------------------------------------------
        safety = SafetyComplianceEngine.evaluate_safety(
            crop=crop_name,
            diagnosed_disease=diagnosis.disease,
            is_healthy=False,
            diagnostic_confidence=diagnosis.confidence,
            treatment=treatment_data,
            days_to_harvest=days_to_harvest,
            co_applied_chemicals=co_applied_chemicals,
        )

        if not treatment_data:
            return FusionRecommendationResponse(
                recommendation_available=False,
                status="NO_REGISTERED_TREATMENT",
                status_message=f"No registered agricultural treatment guideline found for {crop_name} with {diagnosis.disease}.",
                telemetry_summary=telemetry_summary,
                safety_assessment=safety,
                treatment=None,
                dosage_breakdown=None,
                fertilizer_recommendation=fertilizer_rec,
                weather_advisory=weather_adv,
                advisory_notice=DISCLAIMER_ADVISORY,
            )

        treatment_detail = TreatmentDetail(
            active_ingredient=treatment_data["active_ingredient"],
            registered_product_name=treatment_data.get("registered_product_name"),
            chemical_family=treatment_data.get("chemical_family"),
            reference_concentration_Cr=treatment_data["standard_concentration_Cr"],
            concentration_unit=treatment_data.get("concentration_unit", "%"),
            crop_stage=crop_stage,
            application_method=treatment_data.get("application_method", "Foliar Spray"),
            phi_days=treatment_data.get("phi_days", 0),
            ppe_requirements=treatment_data.get("ppe_requirements", ""),
            label_restrictions=treatment_data.get("label_restrictions", ""),
            source_citation=treatment_data.get("source_citation", "Official Extension Guide"),
            official_document=treatment_data.get("official_document"),
            official_citation_detail=treatment_data.get("official_citation_detail"),
            statutory_source_url=treatment_data.get("statutory_source_url"),
            verification_status=treatment_data.get("verification_status", "DEMONSTRATION_UNVERIFIED"),
        )

        # ----------------------------------------------------------------------
        # Step 6: Dosage Computation & Bounded Enforcement
        # ----------------------------------------------------------------------
        dosage_calc = DosageCalculator.compute_dosage(
            treatment=treatment_data,
            severity_result=severity,
            soil_result=soil_resp,
        )

        fert_tip = (
            f"Soil nutrition note: apply {fertilizer_rec['final_prescribed_dose']} {fertilizer_rec['dose_unit']} "
            f"of {fertilizer_rec['product_name']} per acre separately from spraying."
            if fertilizer_rec
            else ""
        )

        # If safety checks failed, suppress actionable prescription
        if not safety.is_safe_to_apply:
            logger.warning(
                "Safety checks failed for (%s, %s): %s. Prescribed dosage suppressed.",
                crop_name, diagnosis.disease, safety.safety_status
            )
            reason = safety.warnings[0] if safety.warnings else safety.safety_status
            farmer_summary = {
                "headline": f"Hold on — do not spray yet ({safety.safety_status.replace('_', ' ').title()}).",
                "what_to_do": reason,
                "how_to_mix": "Chemical spray withheld for crop or harvest safety.",
                "safety_tip": "Show this leaf to your local agricultural officer before spraying.",
                "weather_tip": weather_adv.get("advisory", ""),
                "fertilizer_tip": fert_tip,
                "speech_text": (
                    f"Warning for your {crop_name} crop. Do not spray right now. {reason} "
                    "Please check with your local agricultural officer."
                ),
            }
            return FusionRecommendationResponse(
                recommendation_available=False,
                status=safety.safety_status,
                status_message=f"Treatment cannot be prescribed due to safety or compliance restrictions: {safety.safety_status}",
                telemetry_summary=telemetry_summary,
                safety_assessment=safety,
                treatment=treatment_detail,
                dosage_breakdown=dosage_calc,  # Breakdown included for mathematical transparency
                fertilizer_recommendation=fertilizer_rec,
                weather_advisory=weather_adv,
                farmer_summary=farmer_summary,
                advisory_notice=DISCLAIMER_ADVISORY,
            )

        prod_name = treatment_detail.registered_product_name or treatment_detail.active_ingredient
        farmer_summary = {
            "headline": f"Detected {crop_name} {diagnosis.disease}.",
            "what_to_do": f"Use {prod_name} ({dosage_calc.final_prescribed_dose} {dosage_calc.dose_unit}).",
            "how_to_mix": (
                f"Mix {dosage_calc.final_prescribed_dose} {dosage_calc.dose_unit.split('/')[0]} of {prod_name} "
                f"in {dosage_calc.water_dilution_liters_per_acre:.0f} liters of clean water for 1 acre."
            ),
            "safety_tip": (
                f"Wear {treatment_detail.ppe_requirements}. Wait at least {treatment_detail.phi_days} days after spraying before harvest."
            ),
            "weather_tip": weather_adv.get("advisory", ""),
            "fertilizer_tip": fert_tip,
            "speech_text": (
                f"Your {crop_name} crop shows {diagnosis.disease}. "
                f"Mix {dosage_calc.final_prescribed_dose} {dosage_calc.dose_unit.split('/')[0]} of {prod_name} "
                f"in {dosage_calc.water_dilution_liters_per_acre:.0f} liters of water per acre. "
                f"Wait at least {treatment_detail.phi_days} days before harvesting. "
                f"{weather_adv.get('advisory', '')}"
            ),
        }

        return FusionRecommendationResponse(
            recommendation_available=True,
            status="SUCCESS",
            status_message=f"Verified treatment guideline successfully calculated for {crop_name} {diagnosis.disease}.",
            telemetry_summary=telemetry_summary,
            safety_assessment=safety,
            treatment=treatment_detail,
            dosage_breakdown=dosage_calc,
            fertilizer_recommendation=fertilizer_rec,
            weather_advisory=weather_adv,
            farmer_summary=farmer_summary,
            advisory_notice=DISCLAIMER_ADVISORY,
        )


# Global singleton instance
fusion_service = FusionService()
